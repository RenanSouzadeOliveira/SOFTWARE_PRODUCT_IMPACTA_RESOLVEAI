CREATE TABLE historico_status (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamado_id BIGINT NOT NULL,
    status_anterior VARCHAR(20) NOT NULL,
    status_novo VARCHAR(20) NOT NULL,
    autor_id BIGINT NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacao VARCHAR(500),
    CONSTRAINT fk_historico_status_chamado FOREIGN KEY (chamado_id) REFERENCES chamados (id),
    CONSTRAINT fk_historico_status_autor FOREIGN KEY (autor_id) REFERENCES usuarios (id),
    CONSTRAINT ck_historico_status_transicao CHECK (
        (status_anterior = 'ABERTO' AND status_novo = 'EM_ATENDIMENTO') OR
        (status_anterior = 'EM_ATENDIMENTO' AND status_novo = 'RESOLVIDO') OR
        (status_anterior = 'RESOLVIDO' AND status_novo IN ('EM_ATENDIMENTO', 'FECHADO'))
    ),
    CONSTRAINT ck_historico_status_observacao CHECK (observacao IS NULL OR TRIM(observacao) <> '')
);
CREATE INDEX idx_historico_status_chamado_data_id ON historico_status (chamado_id, criado_em, id);

-- Preserve only evidenced transitions, with original actor and timestamp. Do not infer
-- missing history from the current ticket state or invent explanations for legacy data.
-- DISTINCT avoids a duplicate assignment/status record of the same transition.
INSERT INTO historico_status (chamado_id, status_anterior, status_novo, autor_id, criado_em, observacao)
SELECT DISTINCT chamado_id, status_anterior, status_novo, autor_id, criado_em,
       NULLIF(TRIM(justificativa), '')
FROM historico_chamados
WHERE tipo_evento IN ('ATRIBUICAO', 'STATUS')
  AND ((status_anterior = 'ABERTO' AND status_novo = 'EM_ATENDIMENTO')
    OR (status_anterior = 'EM_ATENDIMENTO' AND status_novo = 'RESOLVIDO')
    OR (status_anterior = 'RESOLVIDO' AND status_novo IN ('EM_ATENDIMENTO', 'FECHADO')))
ORDER BY criado_em, chamado_id;
